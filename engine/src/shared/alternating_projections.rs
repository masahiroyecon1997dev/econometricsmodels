//! 複数のグループ（固定効果）を同時に除く交互射影。
//!
//! 各グループの水準ごとの平均を順に引く掃引を、平均がほぼ0になるまで繰り返すと、列は全グループの
//! ダミー変数への最小二乗の残差（`M_D · x`）に収束する。2つのグループがバランスパネルのように
//! 直交していれば閉形式（二重デミーニング）で済むが、不均衡では掃引の反復が要る。グループの個数は
//! 引数の長さで決まり、2つ（entityとtime）に限らない。
//!
//! 収束を速めるため、掃引2回ごとにIrons–Tuck加速を入れる。グループの索引は
//! [`GroupSystem`]に一度だけ作り、列ごとに使い回す。連結成分（グループの水準を頂点、行を辺とする
//! グラフの連結成分）は[`GroupSystem::components`]で求める。固定効果の復元で、成分ごとに基準を
//! 置くために使う。
//!
//! 重みには対応しない。重み付きの射影は水準ごとの平均が重み付きになるため、`√w`を事前に掛ける
//! 方式では表せない。

